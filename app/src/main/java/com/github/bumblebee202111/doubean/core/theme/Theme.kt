object DoubeanTheme {
    val extendedColors: DoubeanExtendedColors
        @Composable
        @ReadOnlyComposable
        get() = LocalDoubeanExtendedColors.current

    val isDark: Boolean
        @Composable
        @ReadOnlyComposable
        get() = LocalDoubeanDarkTheme.current
}

@Composable
fun DoubeanTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val darkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }
    val context = LocalContext.current
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> darkScheme
        else -> lightScheme
    }
    val extendedColors = if (darkTheme) DarkDoubeanExtendedColors else LightDoubeanExtendedColors

    CompositionLocalProvider(
        LocalDoubeanDarkTheme provides darkTheme,
        LocalDoubeanExtendedColors provides extendedColors,
    ) {
        MaterialExpressiveTheme(
            colorScheme = colorScheme,
            motionScheme = MotionScheme.standard(),
            typography = AppTypography,
            shapes = DoubeanShapes,
            content = content,
        )
    }
}